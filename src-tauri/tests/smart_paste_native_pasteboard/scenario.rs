const TRANSCRIPT: &str = "Handy synthetic transcript α 🦀";
const MARKERS: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

fn rich_fixture() -> Vec<Vec<TypeBytes>> {
    vec![
        vec![
            (
                "public.utf8-plain-text".into(),
                "seed α".as_bytes().to_vec(),
            ),
            ("public.rtf".into(), b"{\\rtf1\\ansi seed}".to_vec()),
            ("com.handy.test.binary".into(), (0..=255).collect()),
        ],
        vec![
            ("public.png".into(), vec![0x89, b'P', b'N', b'G', 0, 1, 2]),
            ("com.handy.test.empty".into(), Vec::new()),
        ],
    ]
}

fn saved(snapshot: &PasteboardSnapshot) -> Vec<Vec<TypeBytes>> {
    snapshot
        .items()
        .iter()
        .map(|item| {
            let types = item.types.iter();
            types.map(|t| (t.uti.clone(), t.data.to_vec())).collect()
        })
        .collect()
}

/// Every seeded type is saved with its exact bytes, in seeded order; AppKit
/// may also report derived types (for example UTF-16 text), saved as read.
fn contains_fixture(saved_types: &[Vec<TypeBytes>]) -> bool {
    let fixture = rich_fixture();
    saved_types.len() == fixture.len()
        && fixture.iter().zip(saved_types).all(|(seeded, saved)| {
            let mut kept = saved.iter().filter(|entry| seeded.contains(entry));
            seeded.iter().all(|entry| kept.next() == Some(entry))
        })
}

fn ensure(condition: bool, message: &str) -> Result<(), String> {
    condition.then_some(()).ok_or_else(|| message.to_string())
}

fn timed_capture(
    harness: &mut Harness,
    budget: SnapshotBudget,
) -> Result<(PasteboardSnapshot, f64), String> {
    let started = Instant::now();
    let snapshot = harness
        .pasteboard
        .capture_snapshot(budget)
        .map_err(|error| format!("capture: {error}"))?;
    Ok((snapshot, started.elapsed().as_secs_f64() * 1000.0))
}

fn publish(harness: &mut Harness, transaction: u64) -> Result<i64, String> {
    let source = harness
        .pasteboard
        .change_count()
        .map_err(|e| e.to_string())?;
    harness
        .pasteboard
        .publish_lazy_transcript(
            TransactionId(transaction),
            &Transcript::new(TRANSCRIPT),
            source,
        )
        .map_err(|error| format!("publish: {error}"))
}

/// Rich multi-item content survives snapshot → lazy publication → external
/// reads → guarded restoration, byte for byte.
fn rich_round_trip(harness: &mut Harness) -> Result<serde_json::Value, String> {
    seed(&harness.name, rich_fixture())?;
    let (snapshot, capture_ms) = timed_capture(harness, SnapshotBudget::default())?;
    let saved_types = saved(&snapshot);
    ensure(
        contains_fixture(&saved_types),
        "seeded types missing from snapshot",
    )?;
    let publication = publish(harness, 1)?;
    let published_types = read_types(&harness.name)?;
    let key_down = harness.now();
    let first = external_read(&harness.name)?;
    let first_reads = harness
        .reads
        .try_iter()
        .filter(|r| r.at >= key_down)
        .count();
    let second = external_read(&harness.name)?;
    let second_reads = harness.reads.try_iter().count();
    let count_after_reads = harness
        .pasteboard
        .change_count()
        .map_err(|e| e.to_string())?;
    let restored = harness
        .pasteboard
        .restore_snapshot(Arc::new(snapshot), publication)
        .map_err(|error| error.to_string())?;
    let is_restored_exactly = read_all(&harness.name)? == saved_types;
    harness.pasteboard.release_transaction(TransactionId(1));
    ensure(
        first == TRANSCRIPT && second == TRANSCRIPT,
        "reader text differs",
    )?;
    ensure(
        first_reads == 1,
        "first external read was not reported once",
    )?;
    ensure(
        restored == GuardedWrite::Written && is_restored_exactly,
        "restore failed",
    )?;
    Ok(json!({
        "check": "rich_round_trip",
        "capture_ms": capture_ms,
        "capture_within_200_ms": capture_ms <= 200.0,
        "saved_types": saved_types.iter().map(|t| t.iter().map(|(u, b)| json!([u, b.len()])).collect::<Vec<_>>()).collect::<Vec<_>>(),
        "published_types": published_types,
        "markers_present": MARKERS.iter().all(|m| published_types.iter().any(|t| t == m)),
        "first_external_read_events": first_reads,
        "second_external_read_events": second_reads,
        "change_count_stable_after_lazy_reads": count_after_reads == publication,
        "restored_exactly": is_restored_exactly,
    }))
}

fn read_types(name: &str) -> Result<Vec<String>, String> {
    // Type names only: reading the data would fulfill the promise in-process.
    let name = name.to_string();
    handy_app_lib::smart_paste::main_thread::run_on_main(
        move || {
            let board = objc2_app_kit::NSPasteboard::pasteboardWithName(
                &objc2_foundation::NSString::from_str(&name),
            );
            let types = board
                .types()
                .map(|types| types.to_vec())
                .unwrap_or_default();
            types.iter().map(|uti| uti.to_string()).collect()
        },
        Duration::from_secs(5),
    )
    .map_err(|error| format!("{error:?}"))
}

/// A copy made after publication is never overwritten by restoration.
fn newer_copy_wins(harness: &mut Harness) -> Result<serde_json::Value, String> {
    seed(&harness.name, rich_fixture())?;
    let (snapshot, _) = timed_capture(harness, SnapshotBudget::default())?;
    let publication = publish(harness, 2)?;
    user_copy(&harness.name, "new text")?;
    let result = harness
        .pasteboard
        .restore_snapshot(Arc::new(snapshot), publication)
        .map_err(|error| error.to_string())?;
    let content = read_all(&harness.name)?;
    harness.pasteboard.release_transaction(TransactionId(2));
    let expected = vec![vec![(
        "public.utf8-plain-text".to_string(),
        b"new text".to_vec(),
    )]];
    ensure(
        result == GuardedWrite::OwnershipChanged,
        "restore did not abandon",
    )?;
    ensure(content == expected, "newer copy was modified")?;
    Ok(
        json!({"check": "newer_copy_wins", "restore": format!("{result:?}"), "newer_copy_intact": true}),
    )
}

/// Materialization leaves eager plain text without privacy markers.
fn materialize_plain_text(harness: &mut Harness) -> Result<serde_json::Value, String> {
    let publication = publish(harness, 3)?;
    let result = harness
        .pasteboard
        .materialize_transcript(&Transcript::new(TRANSCRIPT), publication)
        .map_err(|error| error.to_string())?;
    let content = read_all(&harness.name)?;
    harness.pasteboard.release_transaction(TransactionId(3));
    let expected = vec![vec![(
        "public.utf8-plain-text".to_string(),
        TRANSCRIPT.as_bytes().to_vec(),
    )]];
    ensure(
        result == GuardedWrite::Written && content == expected,
        "materialize failed",
    )?;
    Ok(json!({"check": "materialize_plain_text", "plain_text_only": true}))
}

/// An empty pasteboard is restored as empty.
fn empty_round_trip(harness: &mut Harness) -> Result<serde_json::Value, String> {
    seed(&harness.name, Vec::new())?;
    let (snapshot, _) = timed_capture(harness, SnapshotBudget::default())?;
    ensure(
        snapshot.is_originally_empty(),
        "empty pasteboard not detected",
    )?;
    let publication = publish(harness, 4)?;
    harness
        .pasteboard
        .restore_snapshot(Arc::new(snapshot), publication)
        .map_err(|error| error.to_string())?;
    let is_empty = read_all(&harness.name)?.is_empty();
    harness.pasteboard.release_transaction(TransactionId(4));
    ensure(is_empty, "empty pasteboard not restored as empty")?;
    Ok(json!({"check": "empty_round_trip", "restored_empty": true}))
}

/// A blocking promise is cut at the deadline; completed types are kept.
fn slow_promise_is_bounded(harness: &mut Harness) -> Result<serde_json::Value, String> {
    let eager: TypeBytes = ("public.utf8-plain-text".into(), b"fast".to_vec());
    seed_slow_promise(&harness.name, eager.clone(), "com.handy.test.slow")?;
    let (snapshot, capture_ms) = timed_capture(harness, SnapshotBudget::default())?;
    let causes: Vec<_> = snapshot
        .skipped()
        .iter()
        .map(|s| (s.uti.clone(), s.cause))
        .collect();
    ensure(saved(&snapshot) == vec![vec![eager]], "eager type not kept")?;
    ensure(
        causes == vec![("com.handy.test.slow".to_string(), SkipCause::Timeout)],
        "slow promise not timed out",
    )?;
    // Let the fixture's blocked main-thread promise finish before going on.
    std::thread::sleep(Duration::from_millis(1100));
    Ok(
        json!({"check": "slow_promise_is_bounded", "capture_ms": capture_ms, "slow_type": "Timeout"}),
    )
}

/// Types beyond the byte budget are skipped by name; smaller ones are kept.
fn byte_budget_is_enforced(harness: &mut Harness) -> Result<serde_json::Value, String> {
    let small: TypeBytes = ("com.handy.test.small".into(), vec![7; 10]);
    seed(
        &harness.name,
        vec![vec![
            ("com.handy.test.big".into(), vec![1; 2000]),
            small.clone(),
        ]],
    )?;
    let budget = SnapshotBudget {
        max_bytes: 1000,
        ..SnapshotBudget::default()
    };
    let (snapshot, _) = timed_capture(harness, budget)?;
    let causes: Vec<_> = snapshot
        .skipped()
        .iter()
        .map(|s| (s.uti.clone(), s.cause))
        .collect();
    ensure(saved(&snapshot) == vec![vec![small]], "small type not kept")?;
    ensure(
        causes == vec![("com.handy.test.big".to_string(), SkipCause::Oversize)],
        "big type not skipped",
    )?;
    Ok(json!({"check": "byte_budget_is_enforced", "big_type": "Oversize"}))
}

type Check = fn(&mut Harness) -> Result<serde_json::Value, String>;

/// Runs every scenario on one isolated named pasteboard.
pub fn run_all() -> Result<Vec<serde_json::Value>, String> {
    let cold_ms = helper_first_execution_ms();
    let warm_ms = helper_first_execution_ms();
    let mut harness = harness();
    let checks: [Check; 6] = [
        rich_round_trip,
        newer_copy_wins,
        materialize_plain_text,
        empty_round_trip,
        byte_budget_is_enforced,
        slow_promise_is_bounded,
    ];
    let results: Result<Vec<_>, String> = checks.iter().map(|check| check(&mut harness)).collect();
    release(&harness.name);
    let mut observations = results?;
    observations.insert(
        0,
        json!({"check": "helper_execution", "first_execution_of_new_binary_ms": cold_ms, "warm_execution_ms": warm_ms}),
    );
    Ok(observations)
}
