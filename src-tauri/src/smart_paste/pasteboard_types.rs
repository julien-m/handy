//! Pasteboard type names that change how smart paste saves or restores
//! content: the `org.nspasteboard` privacy markers and the derived types
//! AppKit synthesizes from another type.
//!
//! Pure classification only; the adapters and the coordinator apply it.

// @spec FR-005: Bounded multi-type save — .specs/features/007-smart-paste/spec.md#fr-005
// @spec FR-006: Guarded restoration — .specs/features/007-smart-paste/spec.md#fr-006

/// Marker of content that must not be kept, such as a copied password
/// (nspasteboard.org convention).
pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
/// Marker of content that is only on the pasteboard for a moment.
pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
/// Marker of content written by software rather than by the user.
pub const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";

/// Markers Handy adds to its own temporary transcript items. They are
/// conventions honored by well-behaved clipboard managers, not a guarantee.
pub const HANDY_PRIVACY_MARKERS: [&str; 3] = [TRANSIENT_TYPE, CONCEALED_TYPE, AUTO_GENERATED_TYPE];

/// Whether content carrying `uti` must never be restored.
///
/// Business rule (Julien, 2026-10-13): a dictation changes `changeCount`, so
/// a password manager's automatic clearing no longer fires; restoring a
/// concealed or transient content would leave it on the pasteboard
/// indefinitely. Such content is therefore not restored.
pub fn withholds_restoration(uti: &str) -> bool {
    uti == CONCEALED_TYPE || uti == TRANSIENT_TYPE
}

/// Types AppKit synthesizes by converting another type of the same item
/// (UTF-16 variants of plain text and legacy `NSPasteboard` names). Their
/// conversion can need the owner application, so they are read last.
const DERIVED_TYPES: [&str; 4] = [
    "public.utf16-external-plain-text",
    "public.utf16-plain-text",
    "com.apple.traditional-mac-plain-text",
    "NSStringPboardType",
];

/// Whether `uti` is a type AppKit derives from another type rather than
/// data the owner declared: the fixed list above, dynamic `dyn.` types and
/// legacy Carbon or NeXT names (`… pasteboard type`, `CorePasteboardFlavorType …`).
pub fn is_derived_type(uti: &str) -> bool {
    DERIVED_TYPES.contains(&uti)
        || uti.starts_with("dyn.")
        || uti.ends_with("pasteboard type")
        || uti.starts_with("CorePasteboardFlavorType")
}

/// Order in which the helper reads `(item, type)` pairs: every declared type
/// of every item first, in pasteboard order, then the derived types. A slow
/// conversion can then only cost derived types, never a later item's data.
pub fn read_order(inventory: &[Vec<String>]) -> Vec<(usize, usize)> {
    let pairs = || {
        inventory.iter().enumerate().flat_map(|(item, types)| {
            types
                .iter()
                .enumerate()
                .map(move |(index, uti)| (item, index, is_derived_type(uti)))
        })
    };
    let declared = pairs().filter(|(_, _, derived)| !derived);
    let derived = pairs().filter(|(_, _, derived)| *derived);
    declared
        .chain(derived)
        .map(|(item, index, _)| (item, index))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn inventory(types: &[&[&str]]) -> Vec<Vec<String>> {
        types
            .iter()
            .map(|item| item.iter().map(|uti| uti.to_string()).collect())
            .collect()
    }

    #[test]
    fn concealed_and_transient_withhold_restoration_but_auto_generated_does_not() {
        assert!(withholds_restoration(CONCEALED_TYPE));
        assert!(withholds_restoration(TRANSIENT_TYPE));
        assert!(!withholds_restoration(AUTO_GENERATED_TYPE));
        assert!(!withholds_restoration("public.utf8-plain-text"));
    }

    #[test]
    fn appkit_conversions_and_legacy_names_are_derived() {
        for uti in [
            "public.utf16-external-plain-text",
            "NSStringPboardType",
            "dyn.ah62d4rv4gu8y63n2nuuhg5pbsm4ca6dbsr4gnkduqf31k3pcr7u1e3basv61a3k",
            "Apple PNG pasteboard type",
            "CorePasteboardFlavorType 0x75743136",
        ] {
            assert!(is_derived_type(uti), "{uti}");
        }
        for uti in ["public.utf8-plain-text", "public.rtf", "public.png"] {
            assert!(!is_derived_type(uti), "{uti}");
        }
    }

    #[test]
    fn declared_types_of_every_item_are_read_before_derived_ones() {
        let types = inventory(&[
            &[
                "public.utf8-plain-text",
                "public.utf16-external-plain-text",
                "public.rtf",
            ],
            &["public.png"],
        ]);
        assert_eq!(read_order(&types), vec![(0, 0), (0, 2), (1, 0), (0, 1)]);
    }
}
