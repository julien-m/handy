/// Accept the 0.1-era integer registry index long enough for the schema
/// migration to clear it. Device indices are process-local in transcribe.cpp
/// 0.2 and must never be carried across launches.
fn deserialize_transcribe_gpu_device<'de, D>(deserializer: D) -> Result<Option<String>, D::Error>
where
    D: Deserializer<'de>,
{
    match Option::<serde_json::Value>::deserialize(deserializer)? {
        None => Ok(None),
        Some(serde_json::Value::String(value)) => Ok(Some(value)),
        Some(serde_json::Value::Number(_)) => Ok(None),
        Some(_) => Err(de::Error::custom(
            "transcribe GPU device must be a string, integer, or null",
        )),
    }
}

/// Lenient reading of `automatic_enter`: an unknown value becomes `None` instead of failing the
/// whole store, so a closed build never rewrites the store because of a value it does not read,
/// and an open build's migration turns it into `never` (never a silent Enter).
fn deserialize_automatic_enter<'de, D>(
    deserializer: D,
) -> Result<Option<AutomaticEnterPolicy>, D::Error>
where
    D: Deserializer<'de>,
{
    let value = Option::<serde_json::Value>::deserialize(deserializer)?;
    Ok(value.and_then(|value| serde_json::from_value(value).ok()))
}

/// Lenient reading of `destination_favorites` (012): a value that is not a list reads as no
/// favorite and an unreadable entry is dropped, so one bad entry never fails the whole store.
/// What is dropped is only the unreadable part; the next favorite write stores the clean list.
fn deserialize_destination_favorites<'de, D>(
    deserializer: D,
) -> Result<Vec<crate::destination::favorites::FavoriteApp>, D::Error>
where
    D: Deserializer<'de>,
{
    let value = Option::<serde_json::Value>::deserialize(deserializer)?;
    let entries = match value {
        Some(serde_json::Value::Array(entries)) => entries,
        _ => return Ok(Vec::new()),
    };
    Ok(entries
        .into_iter()
        .filter_map(|entry| serde_json::from_value(entry).ok())
        .collect())
}

/// Lenient reading of `destination_default_inputs` (013), same rule as the favorites: a value that
/// is not a list reads as empty and an unreadable entry is dropped; the next write stores the
/// clean list.
fn deserialize_destination_default_inputs<'de, D>(
    deserializer: D,
) -> Result<Vec<crate::destination::default_input::model::DefaultInput>, D::Error>
where
    D: Deserializer<'de>,
{
    let value = Option::<serde_json::Value>::deserialize(deserializer)?;
    let entries = match value {
        Some(serde_json::Value::Array(entries)) => entries,
        _ => return Ok(Vec::new()),
    };
    Ok(entries
        .into_iter()
        .filter_map(|entry| serde_json::from_value(entry).ok())
        .collect())
}

