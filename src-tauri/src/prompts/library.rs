//! Pure rules and edits of the prompt library (005 AC-001, AC-002, AC-004): validation of a
//! changed prompt, the issues of a stored one, and the typed edits shared by the settings UI
//! commands and the `handy settings prompts` domain. Every edit runs on the locked latest
//! settings and may run twice (preview, then commit), so it never generates anything itself.
use super::types::{PromptError, PromptIssue, MAX_NAME_CHARS, MAX_PROMPTS, MAX_TEXT_CHARS};
use crate::settings::{
    AppSettings, LLMPrompt, PromptProviderOverride, APPLE_INTELLIGENCE_PROVIDER_ID,
};
use crate::settings_service::platform_capability::{PlatformCapabilities, PlatformCapability};
use std::sync::atomic::{AtomicU64, Ordering};

/// The prompt `id`, if any.
pub fn find<'a>(settings: &'a AppSettings, id: &str) -> Option<&'a LLMPrompt> {
    settings
        .post_process_prompts
        .iter()
        .find(|prompt| prompt.id == id)
}

/// New prompt id: creation time plus a process counter, so two creations never share one.
pub fn generate_id() -> String {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let now = chrono::Utc::now();
    let nanos = now
        .timestamp_nanos_opt()
        .unwrap_or_else(|| now.timestamp_millis());
    format!("prompt_{nanos}_{}", COUNTER.fetch_add(1, Ordering::Relaxed))
}

/// Comparable form of a name: trimmed, Unicode lowercase.
fn name_key(name: &str) -> String {
    name.trim().to_lowercase()
}

/// Issue of a name alone (before uniqueness): empty or too long once trimmed, counted in
/// Unicode scalar values, not bytes.
pub fn name_issue(name: &str) -> Option<PromptIssue> {
    let length = name.trim().chars().count();
    if length == 0 {
        Some(PromptIssue::NameEmpty)
    } else if length > MAX_NAME_CHARS {
        Some(PromptIssue::NameTooLong)
    } else {
        None
    }
}

/// Issue of a text: empty or whitespace-only (refused like the settings UI already does), or
/// longer than `MAX_TEXT_CHARS`. The text itself is stored verbatim.
pub fn text_issue(text: &str) -> Option<PromptIssue> {
    if text.trim().is_empty() {
        Some(PromptIssue::TextEmpty)
    } else if text.chars().count() > MAX_TEXT_CHARS {
        Some(PromptIssue::TextTooLong)
    } else {
        None
    }
}

/// Whether another prompt than `id` already uses `name`, ignoring case and outer spaces.
fn is_duplicate(settings: &AppSettings, id: &str, name: &str) -> bool {
    let key = name_key(name);
    settings
        .post_process_prompts
        .iter()
        .any(|other| other.id != id && name_key(&other.name) == key)
}

/// Issue of an override against the providers of `settings`: both fields are required, and the
/// provider must exist in this build.
pub fn override_issue(
    settings: &AppSettings,
    choice: &PromptProviderOverride,
) -> Option<PromptIssue> {
    if choice.provider_id.trim().is_empty() || choice.model.trim().is_empty() {
        return Some(PromptIssue::OverrideIncomplete);
    }
    settings
        .post_process_provider(&choice.provider_id)
        .is_none()
        .then_some(PromptIssue::UnknownProvider)
}

/// Every issue of a stored prompt, in field order. A legacy prompt keeps its issues until it is
/// edited; a prompt with issues is shown but never used for processing.
pub fn issues_of(settings: &AppSettings, prompt: &LLMPrompt) -> Vec<PromptIssue> {
    let duplicate =
        is_duplicate(settings, &prompt.id, &prompt.name).then_some(PromptIssue::NameDuplicate);
    let choice = prompt
        .provider_override
        .as_ref()
        .and_then(|choice| override_issue(settings, choice));
    [
        name_issue(&prompt.name),
        duplicate,
        text_issue(&prompt.prompt),
        choice,
    ]
    .into_iter()
    .flatten()
    .collect()
}

/// Whether `prompt` may process a dictation or become the default.
pub fn is_usable(settings: &AppSettings, prompt: &LLMPrompt) -> bool {
    issues_of(settings, prompt).is_empty()
}

/// Refuse a name or text that would make the prompt `id` invalid.
fn check_fields(
    settings: &AppSettings,
    id: &str,
    name: &str,
    text: &str,
) -> Result<(), PromptError> {
    if let Some(issue) = name_issue(name) {
        return Err(PromptError::Invalid(issue));
    }
    if is_duplicate(settings, id, name) {
        return Err(PromptError::Invalid(PromptIssue::NameDuplicate));
    }
    text_issue(text).map_or(Ok(()), |issue| Err(PromptError::Invalid(issue)))
}

// @spec FR-001: Validated prompt create — .specs/features/005-custom-ai-prompts/spec.md#fr-001
/// Append prompt `id` (generated by the caller with `generate_id`) with the trimmed `name` and
/// the verbatim `text`.
///
/// # Errors
/// `Invalid` for a name or text rule, `LimitExceeded` at `MAX_PROMPTS`.
pub fn create(
    settings: &mut AppSettings,
    id: &str,
    name: &str,
    text: &str,
) -> Result<(), PromptError> {
    check_fields(settings, id, name, text)?;
    if settings.post_process_prompts.len() >= MAX_PROMPTS {
        return Err(PromptError::LimitExceeded);
    }
    let prompt = LLMPrompt::new(id.to_owned(), name.trim().to_owned(), text.to_owned());
    settings.post_process_prompts.push(prompt);
    Ok(())
}

/// Change the name and/or text of prompt `id`; the result must be a fully valid prompt (a legacy
/// prompt is repaired by the edit that changes it).
///
/// # Errors
/// `NotFound`, or `Invalid` for a rule the edited prompt breaks.
pub fn update(
    settings: &mut AppSettings,
    id: &str,
    name: Option<&str>,
    text: Option<&str>,
) -> Result<(), PromptError> {
    let current = find(settings, id).ok_or(PromptError::NotFound)?;
    let name = name.map_or_else(|| current.name.clone(), |name| name.trim().to_owned());
    let text = text.map_or_else(|| current.prompt.clone(), str::to_owned);
    check_fields(settings, id, &name, &text)?;
    if let Some(prompt) = settings
        .post_process_prompts
        .iter_mut()
        .find(|p| p.id == id)
    {
        prompt.name = name;
        prompt.prompt = text;
    }
    Ok(())
}

// @spec FR-001: Delete resets the default to None — .specs/features/005-custom-ai-prompts/spec.md#fr-001
/// Delete prompt `id` (the last one included: the library has no minimum) and its shortcuts.
/// When it was the default, the default becomes None, never another prompt.
///
/// # Errors
/// `NotFound`.
pub fn remove(settings: &mut AppSettings, id: &str) -> Result<(), PromptError> {
    let before = settings.post_process_prompts.len();
    settings
        .post_process_prompts
        .retain(|prompt| prompt.id != id);
    if settings.post_process_prompts.len() == before {
        return Err(PromptError::NotFound);
    }
    // Its shortcuts go in the same revision (AC-006); the running instance releases them first.
    crate::shortcut::prompt_targets::remove_target(settings, id);
    if settings.post_process_selected_prompt_id.as_deref() == Some(id) {
        settings.post_process_selected_prompt_id = None;
    }
    Ok(())
}

/// Make prompt `id` the default, or None with `None`.
///
/// # Errors
/// `NotFound`, or `NotUsable` for a prompt with issues.
pub fn set_default(settings: &mut AppSettings, id: Option<&str>) -> Result<(), PromptError> {
    if let Some(id) = id {
        let prompt = find(settings, id).ok_or(PromptError::NotFound)?;
        if !is_usable(settings, prompt) {
            return Err(PromptError::NotUsable);
        }
    }
    settings.post_process_selected_prompt_id = id.map(str::to_owned);
    Ok(())
}

// @spec FR-006: Set or clear the provider override — .specs/features/005-custom-ai-prompts/spec.md#fr-006
/// Set the provider/model override of prompt `id`, or clear it with `None` (both fields at once,
/// idempotent). Credentials stay with the provider.
///
/// # Errors
/// `NotFound`; `UnsupportedPlatform` for Apple Intelligence off Apple silicon; `Invalid` with
/// `OverrideIncomplete` or `UnknownProvider`.
pub fn set_override(
    settings: &mut AppSettings,
    id: &str,
    choice: Option<PromptProviderOverride>,
    platform: PlatformCapabilities,
) -> Result<(), PromptError> {
    find(settings, id).ok_or(PromptError::NotFound)?;
    let choice = choice.map(|choice| PromptProviderOverride {
        provider_id: choice.provider_id.trim().to_owned(),
        model: choice.model.trim().to_owned(),
    });
    if let Some(choice) = &choice {
        let needs_apple = choice.provider_id == APPLE_INTELLIGENCE_PROVIDER_ID;
        if needs_apple && !platform.supports(PlatformCapability::AppleIntelligence) {
            return Err(PromptError::UnsupportedPlatform);
        }
        if let Some(issue) = override_issue(settings, choice) {
            return Err(PromptError::Invalid(issue));
        }
    }
    if let Some(prompt) = settings
        .post_process_prompts
        .iter_mut()
        .find(|p| p.id == id)
    {
        prompt.provider_override = choice;
    }
    Ok(())
}

