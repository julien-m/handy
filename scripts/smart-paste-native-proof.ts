// Safety bounds include slow compilation/loaded machines, not paste timing claims.
const COMPILER_TIMEOUT_MS = 90_000;
const NATIVE_TIMEOUT_MS = 15_000;

const directory = await mkdtemp(join(tmpdir(), "handy-smart-paste-native-"));
try {
  const provenance = await collectProvenance();
  const swift = join(directory, "main.swift");
  const executable = join(directory, "native-spike");
  await writeFile(swift, source);
  const compiler = await runCommand(
    ["swiftc", swift, "-o", executable],
    COMPILER_TIMEOUT_MS,
    "Swift compilation",
  );
  requireSuccess(compiler, "Swift compilation");
  const binaryHash = hash(await readFile(executable));
  const native = await runCommand(
    [executable],
    NATIVE_TIMEOUT_MS,
    "native fixture",
  );
  requireSuccess(native, "native fixture");
  const report: unknown = JSON.parse(native.stdout.toString());
  if (!isNativeReport(report))
    throw new Error(
      "Native fixture emitted a missing, unknown, or mistyped schema field",
    );
  process.stdout.write(
    `${JSON.stringify({
      ...report,
      ...provenance,
      generated_swift_source_sha256: hash(source),
      compiled_swift_binary_sha256: binaryHash,
      compiler_exit_status: compiler.exitStatus,
      native_exit_status: native.exitStatus,
    })}\n`,
  );
} finally {
  await rm(directory, { recursive: true, force: true });
}
